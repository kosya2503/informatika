def count_letters(text):
    """
    Считает, сколько раз каждая буква встречается в тексте.
    Регистр не учитывается: 'А' и 'а' считаются одной буквой.
    Возвращает словарь: ключ — буква (нижний регистр), значение — количество.
    """
    letter_counts = {}

    # Перебираем все символы текста, предварительно переведя их в нижний регистр
    for char in text.lower():
        # Проверяем, является ли символ буквой (кириллица, латиница и т. д.)
        if char.isalpha():
            # Если буква уже встречалась — увеличиваем счётчик
            if char in letter_counts:
                letter_counts[char] += 1
            # Если это первая встреча буквы — добавляем её в словарь со значением 1
            else:
                letter_counts[char] = 1

    return letter_counts



def calculate_frequency(letter_counts):
    """
    Вычисляет частоту каждой буквы: делит количество на общее число букв.
    Частота округляется до двух знаков после запятой.
    Возвращает новый словарь с частотами.
    """
    # Сначала считаем общее количество букв во всём тексте
    total_letters = 0
    for count in letter_counts.values():
        total_letters += count

    # Создаём словарь для хранения частот
    frequency_dict = {}

    # Для каждой буквы вычисляем частоту и добавляем в итоговый словарь
    for letter, count in letter_counts.items():
        if total_letters > 0:  # Защита от деления на ноль
            frequency = count / total_letters
            frequency_dict[letter] = round(frequency, 2)
        else:
            frequency_dict[letter] = 0.0

    return frequency_dict



# Исходный текст — отрывок из поэмы А. С. Пушкина «Руслан и Людмила»
main_str = """
У лукоморья дуб зелёный;
Златая цепь на дубе том:
И днём и ночью кот учёный
Всё ходит по цепи кругом;
Идёт направо — песнь заводит,
Налево — сказку говорит.
Там чудеса: там леший бродит,
Русалка на ветвях сидит;
Там на неведомых дорожках
Следы невиданных зверей;
Избушка там на курьих ножках
Стоит без окон, без дверей;
Там лес и дол видений полны;
Там о заре прихлынут волны
На брег песчаный и пустой,
И тридцать витязей прекрасных
Чредой из вод выходят ясных,
И с ними дядька их морской;
Там королевич мимоходом
Пленяет грозного царя;
Там в облаках перед народом
Через леса, через моря
Колдун несёт богатыря;
В темнице там царевна тужит,
А бурый волк ей верно служит;
Там ступа с Бабою Ягой
Идёт, бредёт сама собой,
Там царь Кащей над златом чахнет;
Там русский дух… там Русью пахнет!
И там я был, и мёд я пил;
У моря видел дуб зелёный;
Под ним сидел, и кот учёный
Свои мне сказки говорил.
"""

# Шаг 1. Подсчёт количества каждой буквы
letter_counts = count_letters(main_str)

# Шаг 2. Вычисление частоты каждой буквы
frequencies = calculate_frequency(letter_counts)

# Шаг 3. Вывод результата: каждая буква и её частота (на отдельной строке)
for letter, freq in frequencies.items():
    print(f"{letter}: {freq}")
